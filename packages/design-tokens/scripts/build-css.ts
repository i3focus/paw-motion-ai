// Generates tokens.css (Tailwind v4 @theme) from src/index.ts. Run: node scripts/build-css.ts [--check]
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { colors, fontFamily, fontSize, fontWeight, lineHeight, radius, shadows } from '../src/index.ts';

const kebab = (value: string) => value.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();
const lines: string[] = [];
const push = (name: string, value: string | number) => lines.push(`  --${name}: ${value};`);

lines.push('/* Generated by packages/design-tokens/scripts/build-css.ts. Do not edit by hand. */');
lines.push('@theme {');
lines.push('  --color-*: initial;');
lines.push('  --color-transparent: transparent;');
lines.push('  --color-current: currentColor;');
for (const [key, value] of Object.entries(colors)) push(`color-${kebab(key)}`, value);
lines.push('');
push('font-sans', fontFamily.web);
push('font-display', fontFamily.web);
for (const [key, value] of Object.entries(fontWeight)) push(`font-weight-${kebab(key)}`, value);
lines.push('');
for (const [key, value] of Object.entries(fontSize)) push(`text-${kebab(key)}`, `${value}px`);
for (const [key, value] of Object.entries(lineHeight)) push(`leading-${kebab(key)}`, value);
lines.push('');
for (const [key, value] of Object.entries(radius)) push(`radius-${kebab(key)}`, `${value}px`);
lines.push('');
for (const [key, value] of Object.entries(shadows)) push(`shadow-${kebab(key)}`, value.css);
lines.push('}');
lines.push('');

const output = lines.join('\n');
const target = resolve(dirname(fileURLToPath(import.meta.url)), '..', 'tokens.css');

if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== output) {
    console.error('tokens.css is out of date. Run `npm run build` in packages/design-tokens.');
    process.exit(1);
  }
  console.log('tokens.css is up to date.');
} else {
  writeFileSync(target, output);
  console.log(`Wrote ${target}`);
}
